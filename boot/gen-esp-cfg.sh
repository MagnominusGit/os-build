#!/usr/bin/env bash
# retroforge ESP GRUB config generator.
#
#   boot/gen-esp-cfg.sh <outfile>
#
# Emits the config carried in grub-esp.efi's memdisk, the GRUB that OpenABL starts as \EFI\BOOT\bootaa64.efi
# on the shared ESP. It picks the SLOT and hands over to that slot's own stage-2 grub.cfg on its
# efi partition (boot/gen-grub-cfg.sh), which picks the board and boots. Pure text, like
# gen-grub-cfg.sh, so tests/test-stage2-grub.sh generates and checks it on a bare host.
#
# THE SLOT STATE IS RAUC'S. /etc/rauc/system.conf says bootloader=grub, so RAUC keeps ORDER, A_OK,
# A_TRY, B_OK and B_TRY in the ESP's grubenv with grub-editenv, and this reads them the way RAUC's
# reference grub.cfg does, with one difference: TRY counts up to three tries instead of one, so a
# power cut during a long first boot does not throw an update away. RAUC reads any TRY above 0 as
# "not good" and its set-primary, mark-good and mark-bad all write TRY=0, so the extra values mean
# nothing to it.
#
# THE OLD BOOT CONF IS FOLLOWED, NOT OWNED. Roots from before this config re-arm a slot by writing
# \SteamOS\conf\<slot>.conf with steamos-bootconf, and the first update into a root that has this
# config is installed by such a root's hook (RAUC runs the BOOTED root's handler). So when the confs
# select something other than what was seen last time (rf_bcsync in the grubenv), that selection is
# copied into ORDER once. Roots with this config never write the confs, so once no older root is
# left on a device this never fires again.
#
# THE HAND-OVER: this sets $root and $prefix to the chosen slot's efi partition and sources
# $prefix/grub.cfg in the same context, so that config sees $root exactly as when a GRUB is loaded
# off that partition, plus rf_retry/rf_fallback. That is why the stage-2 config needs no change to
# find its disk, and why an older root's stage-2 config still boots that root from here. It runs in
# normal mode (boot/grub.sh enters it from the embedded config), which is what gives it if/for.
set -euo pipefail

OUTFILE="${1:-}"
[ -n "$OUTFILE" ] || { echo "usage: boot/gen-esp-cfg.sh <outfile>" >&2; exit 2; }

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TABLE="$ROOT/image/partition-table.txt"
[ -f "$TABLE" ] || { echo "missing input: $TABLE" >&2; exit 1; }

# Row order IS the partition number on a card (image/genpart.sh); an internal install says where
# its partitions are in parts.env, which overrides these.
part_num() { awk -v n="$1" '/^[[:space:]]*#/||/^[[:space:]]*$/{next} {i++; if ($1==n) {print i; exit}}' "$TABLE"; }
P_EFI_A=$(part_num efi-a); P_EFI_B=$(part_num efi-b)
P_ROOT_A=$(part_num rootfs-a); P_ROOT_B=$(part_num rootfs-b)
for v in P_EFI_A P_EFI_B P_ROOT_A P_ROOT_B; do
  [ -n "${!v}" ] || { echo "cannot resolve $v from ${TABLE#"$ROOT"/}" >&2; exit 1; }
done

cat >"$OUTFILE" <<EOF
# retroforge ESP GRUB — picks the slot. GENERATED by boot/gen-esp-cfg.sh; do not edit.
# In grub-esp.efi's memdisk, which OpenABL starts as \\EFI\\BOOT\\bootaa64.efi on the shared ESP.

insmod part_gpt
insmod fat
insmod btrfs
insmod loadenv
insmod regexp
insmod retroforge

# --- where we are -------------------------------------------------------------------------------
# \$cmdpath is the directory this GRUB was started from, (hd0,gpt1)/EFI/BOOT. Not \$root: with a
# memdisk in the image GRUB points \$root at the memdisk (seen under QEMU/AAVMF).
regexp -s esp '^\\(([^)]+)\\)' "\$cmdpath"
if [ -z "\$esp" ]; then
  echo "retroforge: cannot tell where this GRUB was started from ('\$cmdpath') — searching for the grubenv"
  search --no-floppy --file /EFI/steamos/grubenv --set esp
  sleep 10
fi
set root="\$esp"
regexp -s bootdisk '^([^,]+),gpt[0-9]+\$' "\$esp"
if [ -z "\$bootdisk" ]; then
  echo "retroforge: cannot tell which disk '\$esp' is on — trying hd0"
  sleep 10
  set bootdisk=hd0
fi
set env="(\$esp)/EFI/steamos/grubenv"

# --- where the slots are ------------------------------------------------------------------------
# parts.env says where this medium's partitions are. It is on the ESP of every medium laid out since
# this config shipped; an older one has it only on its efi partitions, so look there next. Only a
# medium retroforge laid out by itself has the built-in indices, which is why they come last.
set efi_a_idx=$P_EFI_A
set efi_b_idx=$P_EFI_B
set root_a_idx=$P_ROOT_A
set root_b_idx=$P_ROOT_B
set pe=""
if [ -f (\$esp)/EFI/steamos/parts.env ]; then
  set pe="(\$esp)/EFI/steamos/parts.env"
else
  for p in (\$bootdisk,gpt*); do
    if [ -f \$p/EFI/steamos/parts.env ]; then
      set pe="\$p/EFI/steamos/parts.env"
      break
    fi
  done
fi
if [ -n "\$pe" ]; then
  load_env -f "\$pe" nd_efi_a nd_efi_b nd_root_a nd_root_b
  if [ -n "\$nd_efi_a" -a -n "\$nd_efi_b" -a -n "\$nd_root_a" -a -n "\$nd_root_b" ]; then
    set efi_a_idx="\$nd_efi_a"
    set efi_b_idx="\$nd_efi_b"
    set root_a_idx="\$nd_root_a"
    set root_b_idx="\$nd_root_b"
  else
    echo "retroforge: \$pe is incomplete — using the built-in partition indices"
    sleep 10
  fi
fi

# --- the slot state -----------------------------------------------------------------------------
load_env -f "\$env" ORDER A_OK A_TRY B_OK B_TRY rf_bcsync

# An older root's boot conf. A conf counts only while it is not marked invalid, and the newer
# boot-requested-at wins (YYYYmmDDHHMMSS, or 0).
retroforge_conf_get (\$esp)/SteamOS/conf/A.conf boot-requested-at bc_a_at
retroforge_conf_get (\$esp)/SteamOS/conf/A.conf image-invalid bc_a_inv
retroforge_conf_get (\$esp)/SteamOS/conf/B.conf boot-requested-at bc_b_at
retroforge_conf_get (\$esp)/SteamOS/conf/B.conf image-invalid bc_b_inv
set bc_a=""
set bc_b=""
if [ -n "\$bc_a_at" ]; then
  if [ -z "\$bc_a_inv" -o "\$bc_a_inv" = 0 ]; then set bc_a=1; fi
fi
if [ -n "\$bc_b_at" ]; then
  if [ -z "\$bc_b_inv" -o "\$bc_b_inv" = 0 ]; then set bc_b=1; fi
fi
set bc_sel=""
if [ -n "\$bc_a" ]; then set bc_sel=A; set bc_at="\$bc_a_at"; fi
if [ -n "\$bc_b" ]; then
  if [ -z "\$bc_sel" ]; then
    set bc_sel=B; set bc_at="\$bc_b_at"
  elif [ "\$bc_b_at" -gt "\$bc_a_at" ]; then
    set bc_sel=B; set bc_at="\$bc_b_at"
  fi
fi
if [ -n "\$bc_sel" ]; then
  if [ "\$bc_sel:\$bc_at" != "\$rf_bcsync" ]; then
    set rf_bcsync="\$bc_sel:\$bc_at"
    set A_OK=0; set A_TRY=0; set B_OK=0; set B_TRY=0
    if [ -n "\$bc_a" ]; then set A_OK=1; fi
    if [ -n "\$bc_b" ]; then set B_OK=1; fi
    if [ "\$bc_sel" = A ]; then set ORDER="A B"; else set ORDER="B A"; fi
    if save_env -f "\$env" ORDER A_OK A_TRY B_OK B_TRY rf_bcsync; then
      true
    else
      echo "retroforge: cannot write \$env — the slot choice will not hold"
      sleep 10
    fi
  fi
fi

# Nothing at all (a lost grubenv): A, then B, both allowed to try.
if [ -z "\$ORDER" ]; then set ORDER="A B"; fi
if [ -z "\$A_OK" ]; then set A_OK=1; fi
if [ -z "\$B_OK" ]; then set B_OK=1; fi

# --- pick ---------------------------------------------------------------------------------------
# The first slot in ORDER that RAUC calls OK, has tries left, and has both a stage-2 config and a
# kernel. The file checks are what keep an empty slot B, or one whose install died halfway, from
# being "chosen" and then failing inside its own config.
set slot=""
set try=""
for s in \$ORDER; do
  if [ "\$s" = A ]; then
    set ok="\$A_OK"; set t="\$A_TRY"; set ei="\$efi_a_idx"; set ri="\$root_a_idx"
  elif [ "\$s" = B ]; then
    set ok="\$B_OK"; set t="\$B_TRY"; set ei="\$efi_b_idx"; set ri="\$root_b_idx"
  else
    continue
  fi
  if [ "\$ok" != 1 ]; then continue; fi
  if [ -n "\$t" -a "\$t" != 0 -a "\$t" != 1 -a "\$t" != 2 ]; then continue; fi
  if [ -f (\$bootdisk,gpt\$ei)/EFI/steamos/grub.cfg -a -f (\$bootdisk,gpt\$ri)/boot/Image ]; then
    set slot="\$s"
    set try="\$t"
    break
  fi
done

export rf_fallback
export rf_retry
set rf_fallback=""
set rf_retry=""
# rf_retry: this slot did not come up last time, so its stage-2 menu shows (a wrong board shows
# itself this way). Booting the second slot in ORDER is not one: after a failed update that is
# every boot until the next one, and the board did not change.
if [ -n "\$slot" ]; then
  if [ "\$try" = 1 -o "\$try" = 2 ]; then set rf_retry=1; fi
  if [ "\$try" = 2 ]; then set nt=3; elif [ "\$try" = 1 ]; then set nt=2; else set nt=1; fi
  # Only the chosen slot's TRY is written: save_env DELETES a variable that is unset here, and RAUC
  # fails every call that reads one that is missing.
  if [ "\$slot" = A ]; then set A_TRY="\$nt"; set tryvar=A_TRY; else set B_TRY="\$nt"; set tryvar=B_TRY; fi
  if save_env -f "\$env" \$tryvar; then
    true
  else
    echo "retroforge: this try of slot \$slot was NOT counted — it cannot fail over to the other"
    sleep 10
  fi
else
  # Nothing has tries left. Boot the LAST slot in ORDER that is OK and complete, without counting
  # it: the first is the one whose tries ran out, so the last is the one that was running before.
  for s in \$ORDER; do
    if [ "\$s" = A ]; then
      set ok="\$A_OK"; set ei="\$efi_a_idx"; set ri="\$root_a_idx"
    elif [ "\$s" = B ]; then
      set ok="\$B_OK"; set ei="\$efi_b_idx"; set ri="\$root_b_idx"
    else
      continue
    fi
    if [ "\$ok" = 1 -a -f (\$bootdisk,gpt\$ei)/EFI/steamos/grub.cfg -a -f (\$bootdisk,gpt\$ri)/boot/Image ]; then
      set slot="\$s"
    fi
  done
  if [ -z "\$slot" ]; then set slot=A; fi
  set rf_fallback=1
  echo "retroforge: no slot has tries left — booting \$slot without counting it"
fi

# --- hand over ----------------------------------------------------------------------------------
if [ "\$slot" = A ]; then
  set root="\$bootdisk,gpt\$efi_a_idx"
else
  set root="\$bootdisk,gpt\$efi_b_idx"
fi
set prefix="(\$root)/EFI/steamos"
source \$prefix/grub.cfg
EOF

echo "  ok   esp.cfg -> ${OUTFILE#"$ROOT"/}"
